"""Persist a skill selection (SKILLS.md + jit.json) and read it back for the capsule."""

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Tuple

from context.skill_selector import Selection

SKILLS_FILENAME = "SKILLS.md"
JIT_JSON_FILENAME = "jit.json"
# Read by Hermes (trusted projects) to narrow the system-prompt skills index.
HERMES_ALLOWLIST_PATH = Path(".hermes") / "skill-allowlist"
MAX_OPTIONAL_POINTERS = 10
HOME_SKIP_REASON = "skipped: $HOME is not a project (and $HOME/.hermes is Hermes' own config dir)"

# (path, mtime) -> parsed "skills" block, so the capsule hook stays cheap.
_POINTER_CACHE: Dict[Tuple[str, float], Dict[str, Any]] = {}


def selection_to_dict(selection: Selection) -> Dict[str, Any]:
    return {
        "must": [pick.name for pick in selection.must],
        "optional": [pick.name for pick in selection.optional],
        "knowhow": [pick.path for pick in selection.knowhow],
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }


def render_skills_md(selection: Selection) -> str:
    lines = [
        "# Project skills",
        "",
        "Generated by `jit init` / `jit skills --write`. Override with `.planning/skills.override.json`.",
        "",
        "| Tier | Skill | Reason | Path |",
        "|------|-------|--------|------|",
    ]
    tiers = (("must", selection.must), ("optional", selection.optional), ("knowhow", selection.knowhow))
    for tier, picks in tiers:
        for pick in picks:
            lines.append(f"| {tier} | {pick.name} | {pick.reason} (score {pick.score}) | {pick.path} |")
    return "\n".join(lines) + "\n"


def is_home_dir(project: Path) -> bool:
    """True when `project` is the user's home directory (never a real project root)."""
    return project.resolve() == Path.home().resolve()


def write_selection(project: Path, selection: Selection) -> Dict[str, str]:
    """Write SKILLS.md and merge the "skills" key into jit.json without clobbering others.

    Refuses $HOME: a stack detected from loose home files is noise, and the Hermes
    allowlist would land in ~/.hermes (Hermes' global config dir).
    """
    if is_home_dir(project):
        return {"skipped": HOME_SKIP_REASON}
    planning = project / ".planning"
    planning.mkdir(parents=True, exist_ok=True)
    skills_file = planning / SKILLS_FILENAME
    skills_file.write_text(render_skills_md(selection), encoding="utf-8")
    profile_file = planning / JIT_JSON_FILENAME
    try:
        profile = json.loads(profile_file.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        profile = {}
    profile["skills"] = selection_to_dict(selection)
    profile_file.write_text(json.dumps(profile, indent=2) + "\n", encoding="utf-8")
    allowlist_file = write_hermes_allowlist(project, selection)
    return {"skills_md": str(skills_file), "profile": str(profile_file), "allowlist": str(allowlist_file)}


def write_hermes_allowlist(project: Path, selection: Selection) -> Path:
    """Write <project>/.hermes/skill-allowlist (must + optional) for Hermes' per-project skills index.

    Hermes reads it only for trusted projects (`hermes skills trust`); it narrows the prompt
    index, while skill_view can still load any skill by name.
    """
    allowlist_file = project / HERMES_ALLOWLIST_PATH
    allowlist_file.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Generated by `jit skills --write` (jit-context). Must-have first, then optional."]
    lines += [pick.name for pick in selection.must]
    lines += [pick.name for pick in selection.optional]
    allowlist_file.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return allowlist_file


def _load_skills_block(profile_file: Path) -> Dict[str, Any]:
    key = (str(profile_file), profile_file.stat().st_mtime)
    if key not in _POINTER_CACHE:
        try:
            data = json.loads(profile_file.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            data = {}
        block = data.get("skills") if isinstance(data, dict) else None
        _POINTER_CACHE[key] = block if isinstance(block, dict) else {}
    return _POINTER_CACHE[key]


def skill_pointers(project_dir: str) -> List[str]:
    """Capsule pointer lines: one `@skill:<name>` per must-have, one `@skills:optional:` line."""
    profile_file = Path(project_dir) / ".planning" / JIT_JSON_FILENAME
    if not profile_file.is_file():
        return []
    block = _load_skills_block(profile_file)
    pointers = [f"@skill:{name}" for name in block.get("must", [])]
    optional = block.get("optional", [])[:MAX_OPTIONAL_POINTERS]
    if optional:
        pointers.append("@skills:optional: " + ", ".join(optional))
    return pointers
