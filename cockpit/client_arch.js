// Architecture interactions use actual SVG dimensions in both viewports.
function getArchScript() {
  return `
function archElements() {
  const full = document.getElementById('arch-fullscreen-modal')?.classList.contains('open');
  return { view: document.getElementById(full ? 'fs-arch-viewport' : 'arch-viewport'), inner: document.getElementById(full ? 'fs-arch-svg-inner' : 'arch-svg-inner') };
}
function applyArchTransform() {
  const { inner } = archElements();
  if (inner) inner.style.transform = 'translate(' + archPanX + 'px,' + archPanY + 'px) scale(' + archScale + ')';
  const indicator = document.getElementById('zoom-indicator');
  if (indicator) indicator.textContent = Math.round(archScale * 100) + '%';
}
function fitArchZoom() {
  const { view, inner } = archElements();
  const svg = inner?.querySelector('svg');
  if (!svg || !view?.clientWidth) return;
  const box = svg.viewBox.baseVal;
  const width = box.width || 800, height = box.height || 500;
  svg.style.width = width + 'px'; svg.style.height = height + 'px';
  archScale = Math.min((view.clientWidth - 70) / width, (view.clientHeight - 60) / height, 2);
  archPanX = (view.clientWidth - width * archScale) / 2;
  archPanY = (view.clientHeight - height * archScale) / 2;
  applyArchTransform();
}
function zoomArch(factor) {
  const { view } = archElements();
  if (!view) return;
  zoomArchAt(factor, view.clientWidth / 2, view.clientHeight / 2);
}
function zoomArchAt(factor, x, y) {
  const next = Math.max(0.15, Math.min(8, archScale * factor));
  const ratio = next / archScale;
  archPanX = x - (x - archPanX) * ratio;
  archPanY = y - (y - archPanY) * ratio;
  archScale = next; applyArchTransform();
}
function resetArchZoom() { archScale = 1; archPanX = 30; archPanY = 30; applyArchTransform(); }
function bindArchViewport(view) {
  if (!view || view.dataset.bound) return;
  view.dataset.bound = 'true';
  view.addEventListener('wheel', event => {
    event.preventDefault(); const box = view.getBoundingClientRect();
    zoomArchAt(event.deltaY < 0 ? 1.12 : 1 / 1.12, event.clientX - box.left, event.clientY - box.top);
  }, { passive: false });
  let drag = null;
  view.addEventListener('pointerdown', event => {
    if (event.button !== 0) return;
    drag = { x: event.clientX, y: event.clientY, panX: archPanX, panY: archPanY };
    view.setPointerCapture(event.pointerId);
  });
  view.addEventListener('pointermove', event => {
    if (!drag) return;
    archPanX = drag.panX + event.clientX - drag.x;
    archPanY = drag.panY + event.clientY - drag.y;
    applyArchTransform();
  });
  const release = () => { drag = null; };
  view.addEventListener('pointerup', release); view.addEventListener('pointercancel', release);
}
function attachMermaidNodeListeners() {
  document.querySelectorAll('.mermaid svg .node').forEach(node => {
    node.style.cursor = 'pointer'; node.setAttribute('tabindex', '0');
    const inspect = () => {
      const inspector = document.getElementById('arch-node-details');
      if (inspector) inspector.textContent = node.textContent.trim() + ' — źródło: ' + COCKPIT_DATA.architectureMeta.source + '. Etykieta z dokumentacji; brak niezależnego testu usługi.';
    };
    node.onclick = inspect;
    node.onkeydown = event => { if (event.key === 'Enter') inspect(); };
  });
}
let architectureRendering = null;
async function initMermaidPanZoom() {
  const viewport = document.getElementById('arch-viewport');
  if (!viewport?.clientWidth) return;
  const diagram = viewport.querySelector('.mermaid');
  if (!diagram.querySelector('svg')) {
    if (!architectureRendering) architectureRendering = mermaid.render('project-architecture-detail', COCKPIT_DATA.architecture);
    try {
      const { svg } = await architectureRendering;
      // SVG is generated by bundled Mermaid with securityLevel strict; not model HTML.
      const documentSvg = new DOMParser().parseFromString(svg, 'image/svg+xml').documentElement;
      diagram.replaceChildren(document.importNode(documentSvg, true));
    } catch {
      diagram.textContent = COCKPIT_DATA.architecture;
      document.getElementById('arch-node-details').textContent = 'Nie udało się wyrenderować SVG. Poniżej jest rzeczywiste źródło diagramu.';
      architectureRendering = null; return;
    }
  }
  bindArchViewport(viewport);
  bindArchViewport(document.getElementById('fs-arch-viewport'));
  attachMermaidNodeListeners();
  requestAnimationFrame(fitArchZoom);
}
function openArchFullscreen() {
  const source = document.getElementById('arch-svg-inner');
  const target = document.getElementById('fs-arch-svg-inner');
  target.replaceChildren(...[...source.childNodes].map(node => node.cloneNode(true)));
  document.getElementById('arch-fullscreen-modal').classList.add('open');
  initMermaidPanZoom();
}
function closeArchFullscreen() {
  document.getElementById('arch-fullscreen-modal')?.classList.remove('open');
  requestAnimationFrame(fitArchZoom);
}
window.addEventListener('resize', () => { if (document.getElementById('pane-arch')?.classList.contains('active')) fitArchZoom(); });
`;
}
module.exports = { getArchScript };
